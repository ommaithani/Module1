# Write a Python program to demonstrate the creation of variables and different data types.

# string
name="Om Maithani"
print(name)
print(type(name))

# integer
a=10
print(a)
print(type(a))

# boolean
yourageis=True
print("Above 18",yourageis)
print(type(yourageis))

# Float
b=1.1
print(b)
print(type(b))

# list
fruits=["apple","banana","mango"]
print(fruits)
print(type(fruits))

# Dictionary
profile={
    'username':'om maithani',
    'course':'python',
    'batch':'5 may'
}
print(profile)
print(type(profile))

# tuple
Days=('Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday')
print("First day of week is :",Days[0])
print("Last day of week is :",Days[6])
print(type(Days))





